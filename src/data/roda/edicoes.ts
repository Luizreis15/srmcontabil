export const formatarData = (iso: string | null, texto?: string) => {
  if (!iso) return texto ?? "Data a definir";
  return new Date(iso).toLocaleDateString("pt-BR", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "America/Sao_Paulo",
  });
};
